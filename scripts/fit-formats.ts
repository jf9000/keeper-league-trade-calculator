/**
 * Fits how much each position's ADP shifts between PPR and the standard / half-PPR formats, from real ADP in
 * data/archive (Fantasy Football Calculator). Run with `npm run fit-formats` (add `--write` to write
 * src/lib/formatAdp.ts). Offline only.
 *
 * The shift is a per-position multiplier on PPR ADP: the median of (format ADP / PPR ADP) over players drafted
 * in both, within the first 12 rounds' worth of picks (later picks are too noisy to say anything).
 */
import { writeFileSync } from 'node:fs'
import { loadArchives } from './backtestLib'

const POS = ['QB', 'RB', 'WR', 'TE'] as const
const FORMATS = [
  { key: 'std', field: 'adpStd' },
  { key: 'half', field: 'adpHalf' },
] as const
/** Hand-set multipliers the app used before this fit, for comparison. */
const OLD: Record<string, Record<string, number>> = {
  std: { QB: 1, RB: 0.95, WR: 1.08, TE: 1.08 },
  half: { QB: 1, RB: 1, WR: 1, TE: 1 },
}
const MAX_ADP = 144

const median = (v: number[]) => {
  const s = [...v].sort((a, b) => a - b)
  return s.length ? (s.length % 2 ? s[(s.length - 1) / 2]! : (s[s.length / 2 - 1]! + s[s.length / 2]!) / 2) : NaN
}

const archives = loadArchives()
const fitted: Record<string, Record<string, number>> = {}
for (const f of FORMATS) {
  fitted[f.key] = {}
  console.log(`\n${f.key}: position  n  fitted  hand-set  mean|log error| fitted vs hand-set`)
  for (const pos of POS) {
    const ratios: number[] = []
    for (const a of archives) {
      for (const p of Object.values(a.players)) {
        const x = p[f.field]
        if (p.pos !== pos || x === undefined || p.adp === undefined || p.adp > MAX_ADP) continue
        ratios.push(x / p.adp)
      }
    }
    const m = ratios.length >= 15 ? median(ratios) : 1
    fitted[f.key]![pos] = Math.round(m * 100) / 100
    const err = (mult: number) => ratios.reduce((t, r) => t + Math.abs(Math.log(r / mult)), 0) / Math.max(1, ratios.length)
    console.log(`  ${pos}  ${String(ratios.length).padStart(4)}  ${m.toFixed(3)}  ${OLD[f.key]![pos]!.toFixed(2)}  ${err(m).toFixed(3)} vs ${err(OLD[f.key]![pos]!).toFixed(3)}`)
  }
}

if (process.argv.includes('--write')) {
  const rows = FORMATS.map((f) => `  ${f.key}: { ${POS.map((p) => `${p}: ${fitted[f.key]![p]}`).join(', ')} },`).join('\n')
  writeFileSync(
    'src/lib/formatAdp.ts',
    `// Generated by scripts/fit-formats.ts from data/archive (${archives[0]!.season}-${archives[archives.length - 1]!.season}). Do not edit by hand.\n` +
      `/** Multiplier on a player's PPR ADP in standard and half-PPR leagues, by position. Above 1 means he goes later. */\n` +
      `export const FORMAT_ADP: Record<'std' | 'half', Record<'QB' | 'RB' | 'WR' | 'TE', number>> = {\n${rows}\n}\n`,
  )
  console.log('\nWrote src/lib/formatAdp.ts')
}
